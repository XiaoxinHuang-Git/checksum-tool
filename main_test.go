package main

import (
	"os"
	"path/filepath"
	"testing"
)

func TestHashFile(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "hello.txt")
	if err := os.WriteFile(p, []byte("hello"), 0o644); err != nil {
		t.Fatal(err)
	}

	got, err := hashFile(p)
	if err != nil {
		t.Fatal(err)
	}

	const want = "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824"
	if got != want {
		t.Fatalf("hash mismatch: got %s want %s", got, want)
	}
}

func TestParseLine(t *testing.T) {
	const sum = "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824"

	cases := []struct {
		name string
		line string
		ok   bool
		path string
	}{
		{"标准两空格", sum + "  dir/a.txt", true, "dir/a.txt"},
		{"二进制标记", sum + " *dir/a.txt", true, "dir/a.txt"},
		{"带空格的路径", sum + "  my documents/a b.txt", true, "my documents/a b.txt"},
		{"空行", "", false, ""},
		{"注释", "# generated by checksum-tool", false, ""},
		{"哈希非法", "zzzz4dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824  a.txt", false, ""},
		{"缺少路径", sum, false, ""},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			e, ok := parseLine(c.line)
			if ok != c.ok {
				t.Fatalf("ok = %v, want %v", ok, c.ok)
			}
			if ok && e.path != c.path {
				t.Fatalf("path = %q, want %q", e.path, c.path)
			}
		})
	}
}

func TestCollectSkipsManifestAndGit(t *testing.T) {
	dir := t.TempDir()
	sub := filepath.Join(dir, "sub")
	if err := os.MkdirAll(sub, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, ".git"), 0o755); err != nil {
		t.Fatal(err)
	}
	write := func(p, s string) {
		if err := os.WriteFile(p, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(dir, "a.txt"), "a")
	write(filepath.Join(sub, "b.txt"), "b")
	write(filepath.Join(dir, ".git", "config"), "ignored")

	manifest := filepath.Join(dir, defaultManifest)
	write(manifest, "should be skipped")

	entries, err := collect(dir, manifest)
	if err != nil {
		t.Fatal(err)
	}

	if len(entries) != 2 {
		t.Fatalf("expected 2 entries, got %d: %+v", len(entries), entries)
	}
	if entries[0].path != "a.txt" || entries[1].path != "sub/b.txt" {
		t.Fatalf("unexpected order: %+v", entries)
	}
}

func TestManifestRoundTrip(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "x.bin"), []byte("payload"), 0o644); err != nil {
		t.Fatal(err)
	}

	manifest := filepath.Join(dir, defaultManifest)
	entries, err := collect(dir, manifest)
	if err != nil {
		t.Fatal(err)
	}
	if err := writeManifest(manifest, entries); err != nil {
		t.Fatal(err)
	}

	parsed, err := readManifest(manifest)
	if err != nil {
		t.Fatal(err)
	}
	if len(parsed) != 1 {
		t.Fatalf("expected 1 entry, got %d", len(parsed))
	}
	if parsed[0].hash != entries[0].hash || parsed[0].path != "x.bin" {
		t.Fatalf("round trip mismatch: %+v vs %+v", parsed[0], entries[0])
	}
}
